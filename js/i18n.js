  // Lookup translation
  t(key) {
    const lang = this.translations[this.current];
    const en   = this.translations['en'];
    return (lang && lang[key]) || (en && en[key]) || key;
  },

  // Change current language and apply everywhere
  setLanguage(lang) {
    if (!this.translations[lang]) {
      // For languages without full dictionary, fall back to English or closest
      console.warn('Language not fully translated, falling back:', lang);
    }
    this.current = lang || 'en';
    DB.setSettings({ language: this.current });

    // 1. Update DOM text & placeholders
    this.applyToDOM();

    // 2. Synchronize all select elements
    document.querySelectorAll('#languageSelect, #setupLanguage').forEach(sel => {
      if (sel) sel.value = this.current;
    });

    // 3. Trigger full application re-render
    if (typeof App !== 'undefined' && App.onLanguageChanged) {
      App.onLanguageChanged(this.current);
    }
  },

  // Apply translations to all DOM elements with data-i18n attributes
  applyToDOM() {
    // 1. Plain text and container nodes
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const val = this.t(key);
      if (!val) return;

      // If this element has special child icon elements (like .nav-icon or .btn-icon)
      const icon = el.querySelector('.nav-icon, .btn-icon, .mic-icon, .kpi-icon, .report-icon');
      const label = el.querySelector('.nav-label, .btn-text, .kpi-label');

      if (label) {
        label.textContent = val;
      } else if (icon) {
        const iconClone = icon.cloneNode(true);
        el.innerHTML = '';
        el.appendChild(iconClone);
        el.appendChild(document.createTextNode(' ' + val));
      } else {
        el.textContent = val;
      }
    });

    // 2. Placeholder attributes
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      const val = this.t(key);
      if (val) el.placeholder = val;
    });

    // 3. Title attributes
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      const val = this.t(key);
      if (val) el.title = val;
    });

    // 4. Select options with data-i18n
    document.querySelectorAll('option[data-i18n]').forEach(opt => {
      const key = opt.getAttribute('data-i18n');
      const val = this.t(key);
      if (val) opt.textContent = val;
    });

    // 5. Update HTML lang attribute
    document.documentElement.lang = this.current;
  },

  // Get localized greeting based on time of day
  getGreeting() {
    const h = new Date().getHours();
    if (h < 12) return this.t('good_morning');
    if (h < 17) return this.t('good_afternoon');
    return this.t('good_evening');
  },

  // Format currency with Nigerian Naira symbol
  formatCurrency(amount) {
    return '₦' + Number(amount || 0).toLocaleString('en-NG', { minimumFractionDigits: 0 });
  },

  // Detect language heuristic for input text
  detectLanguage(text) {
    const yoruba = /[ẹọṣẹ̀ẹ́ọ̀ọ́]|(\b(bawo|owo|ti|lori|se|fun|kini|mo|ta|epo|iresi|ojo|ere|gbese)\b)/i;
    const igbo   = /[ụịọ]|(\b(kedu|ego|maka|anyi|ahia|ugwo|onye|otu|taa)\b)/i;
    const hausa  = /[ɗƙ]|(\b(sannu|kudi|riba|bashi|nawa|yau|shago|kaya|mai)\b)/i;
    const pidgin = /\b(wetin|dey|abeg|omo|no be|nah|wahala|sha|how far|fit|kuku|sharp)\b/i;

    if (yoruba.test(text)) return 'yo';
    if (igbo.test(text))   return 'ig';
    if (hausa.test(text))  return 'ha';
    if (pidgin.test(text)) return 'pcm';
    return this.current || 'en';
  }
